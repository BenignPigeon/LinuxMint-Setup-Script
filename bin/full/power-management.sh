#!/usr/bin/env bash
# power-management.sh — Framework 13 AMD suspend fix
# Disables spurious wakeup sources that cause the laptop to wake in your bag
# and optionally installs acpica-tools for deeper amd-s2idle diagnostics.
#
# Usage:
#   sudo ./power-management.sh            — apply fixes (persistent via udev)
#   sudo ./power-management.sh --revert   — remove udev rule and restore defaults
#   sudo ./power-management.sh --status   — show current wakeup source states
#   sudo ./power-management.sh --test     — apply + run amd-s2idle test cycle

set -euo pipefail

# ── Colour helpers ────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; RESET='\033[0m'
ok()   { echo -e "${GREEN}✅  $*${RESET}"; }
warn() { echo -e "${YELLOW}👀  $*${RESET}"; }
err()  { echo -e "${RED}❌  $*${RESET}"; }
info() { echo -e "${CYAN}ℹ️   $*${RESET}"; }
banner() { echo -e "\n${BOLD}$*${RESET}"; }

# ── Sanity checks ─────────────────────────────────────────────────────────────
if [[ $EUID -ne 0 ]]; then
    err "This script must be run as root (use sudo)."
    exit 1
fi

UDEV_RULE=/etc/udev/rules.d/99-framework-suspend-wakeup.rules
LOGIND_CONF=/etc/systemd/logind.conf.d/framework-lid.conf

# ── Wakeup sources to DISABLE ─────────────────────────────────────────────────
# These are the sources most likely to wake the laptop while it's in your bag.
# Touchpad mouse wakes on any slight movement; USB/TB controllers on any plug event.
declare -A WAKEUP_DISABLE=(
    # Touchpad (PIXA3854) — primary bag-wake culprit
    ["touchpad"]="/sys/bus/i2c/devices/i2c-PIXA3854:00/power/wakeup"
    # USB controllers — wake on any USB event
    ["usb_xhc0"]="/sys/bus/pci/devices/0000:c1:00.3/power/wakeup"
    ["usb_xhc1"]="/sys/bus/pci/devices/0000:c1:00.4/power/wakeup"
    ["usb_xhc3"]="/sys/bus/pci/devices/0000:c3:00.3/power/wakeup"
    ["usb_xhc4"]="/sys/bus/pci/devices/0000:c3:00.4/power/wakeup"
    # Thunderbolt domains — wake on dock/cable events
    ["thunderbolt0"]="/sys/bus/thunderbolt/devices/domain0/power/wakeup"
    ["thunderbolt1"]="/sys/bus/thunderbolt/devices/domain1/power/wakeup"
)

# ── Wakeup sources to KEEP enabled ────────────────────────────────────────────
# Power button, lid switch, keyboard, RTC alarm stay on so you can wake normally.

# ── Functions ─────────────────────────────────────────────────────────────────

apply_wakeup_fixes() {
    banner "Disabling spurious wakeup sources..."
    local any_missing=0

    for name in "${!WAKEUP_DISABLE[@]}"; do
        local path="${WAKEUP_DISABLE[$name]}"
        if [[ -f "$path" ]]; then
            echo "disabled" > "$path"
            ok "Disabled wakeup: $name"
        else
            warn "Path not found (may be OK if device absent): $path"
            any_missing=1
        fi
    done

    [[ $any_missing -eq 1 ]] && warn "Some paths were missing — harmless if those devices aren't present."
}

install_udev_rule() {
    banner "Installing persistent udev rule → $UDEV_RULE"
    mkdir -p "$(dirname "$UDEV_RULE")"

    cat > "$UDEV_RULE" << 'EOF'
# Framework 13 AMD — disable wakeup sources that trigger in-bag wake events.
# Generated by power-management.sh

# Touchpad (PIXA3854) — most common bag-wake cause
ACTION=="add", SUBSYSTEM=="i2c", ATTR{name}=="PIXA3854:00 093A:0274 Mouse",    ATTR{power/wakeup}="disabled"
ACTION=="add", SUBSYSTEM=="i2c", ATTR{name}=="PIXA3854:00 093A:0274 Touchpad", ATTR{power/wakeup}="disabled"

# USB controllers
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x1022", ATTR{device}=="0x15b9", ATTR{power/wakeup}="disabled"
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x1022", ATTR{device}=="0x15ba", ATTR{power/wakeup}="disabled"
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x1022", ATTR{device}=="0x15c0", ATTR{power/wakeup}="disabled"
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x1022", ATTR{device}=="0x15c1", ATTR{power/wakeup}="disabled"

# Thunderbolt / USB4
ACTION=="add", SUBSYSTEM=="thunderbolt", ATTR{power/wakeup}="disabled"
EOF

    ok "udev rule written. Will persist across reboots."
    udevadm control --reload-rules
    ok "udev rules reloaded."
}

configure_logind() {
    banner "Configuring logind lid-close behaviour..."
    mkdir -p "$(dirname "$LOGIND_CONF")"

    if [[ -f "$LOGIND_CONF" ]]; then
        info "logind config already exists — skipping (edit $LOGIND_CONF manually if needed)."
        return
    fi

    cat > "$LOGIND_CONF" << 'EOF'
# Framework 13 AMD — ensure lid close always suspends
# Generated by power-management.sh
[Login]
HandleLidSwitch=suspend
HandleLidSwitchExternalPower=suspend
HandleLidSwitchDocked=ignore
EOF

    ok "logind lid config written."
    systemctl restart systemd-logind
    ok "systemd-logind restarted."
}

install_acpica() {
    banner "Checking for acpica-tools (iasl)..."
    if command -v iasl &>/dev/null; then
        ok "iasl already installed: $(command -v iasl)"
        return
    fi

    info "Installing acpica-tools for deeper amd-s2idle diagnostics..."
    if apt-get install -y acpica-tools &>/dev/null; then
        ok "acpica-tools installed."
    else
        warn "Could not install acpica-tools automatically. Run: sudo apt install acpica-tools"
    fi
}

show_status() {
    banner "Current wakeup source states"
    printf "%-20s %-12s %s\n" "NAME" "STATE" "PATH"
    printf "%-20s %-12s %s\n" "----" "-----" "----"

    for name in "${!WAKEUP_DISABLE[@]}"; do
        local path="${WAKEUP_DISABLE[$name]}"
        if [[ -f "$path" ]]; then
            local state
            state=$(cat "$path")
            if [[ "$state" == "disabled" ]]; then
                printf "${GREEN}%-20s %-12s${RESET} %s\n" "$name" "$state" "$path"
            else
                printf "${YELLOW}%-20s %-12s${RESET} %s\n" "$name" "$state" "$path"
            fi
        else
            printf "${RED}%-20s %-12s${RESET} %s\n" "$name" "missing" "$path"
        fi
    done

    echo ""
    banner "logind lid configuration"
    if [[ -f "$LOGIND_CONF" ]]; then
        cat "$LOGIND_CONF"
    else
        warn "No custom logind config found at $LOGIND_CONF"
        info "Active lid setting:"
        loginctl show-seat seat0 2>/dev/null | grep -i lid || true
    fi

    echo ""
    banner "udev rule"
    if [[ -f "$UDEV_RULE" ]]; then
        ok "Rule present: $UDEV_RULE"
    else
        warn "No udev rule found at $UDEV_RULE (fixes won't persist after reboot)"
    fi
}

revert() {
    banner "Reverting changes..."

    if [[ -f "$UDEV_RULE" ]]; then
        rm -f "$UDEV_RULE"
        udevadm control --reload-rules
        ok "Removed udev rule: $UDEV_RULE"
    else
        info "No udev rule to remove."
    fi

    if [[ -f "$LOGIND_CONF" ]]; then
        rm -f "$LOGIND_CONF"
        systemctl restart systemd-logind
        ok "Removed logind config: $LOGIND_CONF"
    else
        info "No logind config to remove."
    fi

    banner "Re-enabling wakeup sources..."
    for name in "${!WAKEUP_DISABLE[@]}"; do
        local path="${WAKEUP_DISABLE[$name]}"
        if [[ -f "$path" ]]; then
            echo "enabled" > "$path"
            ok "Re-enabled: $name"
        fi
    done

    ok "Revert complete. Original wakeup behaviour restored."
}

run_test() {
    if ! command -v amd-s2idle &>/dev/null; then
        # Try common install location used by amd-s2idle pip install
        if [[ -f /root/.local/bin/amd-s2idle ]]; then
            AMD_S2IDLE=/root/.local/bin/amd-s2idle
        else
            err "amd-s2idle not found. Install with: pip install amd-s2idle"
            exit 1
        fi
    else
        AMD_S2IDLE=$(command -v amd-s2idle)
    fi

    banner "Running amd-s2idle suspend test..."
    "$AMD_S2IDLE" test
}

# ── Argument dispatch ─────────────────────────────────────────────────────────
MODE="${1:-apply}"

case "$MODE" in
    --revert)
        revert
        ;;
    --status)
        show_status
        ;;
    --test)
        apply_wakeup_fixes
        install_udev_rule
        configure_logind
        install_acpica
        echo ""
        ok "Fixes applied. Launching suspend test..."
        run_test
        ;;
    apply|--apply)
        banner "Framework 13 AMD — Power Management Fix"
        info "This will disable touchpad/USB/Thunderbolt wakeup sources"
        info "and ensure lid-close always suspends."
        echo ""
        apply_wakeup_fixes
        install_udev_rule
        configure_logind
        install_acpica
        echo ""
        ok "All done! Fixes applied and will persist across reboots."
        info "Run with --status to verify, --revert to undo, --test to run amd-s2idle."
        ;;
    *)
        echo "Usage: sudo $0 [--apply|--revert|--status|--test]"
        exit 1
        ;;
esac